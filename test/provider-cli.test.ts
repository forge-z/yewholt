const hidden = "private-environment-fixture";

function fixture(t: { after(fn: () => void): void }) {
  const home = mkdtempSync(join(homedir(), "yewholt-provider-cli-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const bin = join(home, "bin with 'quotes'");
  const config = join(home, "xdg", "yewholt");
  const env = { PATH: process.env.PATH, HOME: home, XDG_CONFIG_HOME: join(home, "xdg"),
    YEWHOLT_HOME: home, YEWHOLT_PROVIDER_BIN_DIR: bin, YEWHOLT_PROVIDER_FILE_STORAGE: "1" };
  const run = (...args: string[]) => {
    const result = spawnSync(process.execPath, [cli, ...args], { env, encoding: "utf8", timeout: 5_000 });
    assert.equal(result.error, undefined);
    assert.ok(![agent.secret, hidden].some((value) => (result.stdout + result.stderr).includes(value)));
    return result;
  };
  const legacy = (id: string) => join(bin, "buzz-backend-yewholt-" + id);
  const target = (id: string) => join(config, "targets", id + ".json");
  return { home, bin, config, env, run, legacy, target };
}

test("provider install, target add, pair and remove end to end; install deletes old managed shims only", (t) => {
  const { bin, config, run, legacy, target } = fixture(t);
  mkdirSync(bin, { recursive: true });
  const managed = "#!/bin/sh\n# Managed by yewholt\nexit 0\n";
  writeFileSync(legacy("mac"), managed, { mode: 0o700 });
  writeFileSync(join(bin, "yewholt-provider-engine"), managed, { mode: 0o700 });
  writeFileSync(legacy("foreign"), "not generated by Yewholt", { mode: 0o700 });
  const initial = run("provider", "install");
  assert.equal(initial.status, 0, initial.stderr);
  assert.equal(existsSync(legacy("mac")), false);
  assert.equal(existsSync(join(bin, "yewholt-provider-engine")), false);
  assert.equal(readFileSync(legacy("foreign"), "utf8"), "not generated by Yewholt");
  assert.equal(statSync(join(bin, "yewholt-buzz-bridge")).mode & 0o777, 0o700);
  const key = JSON.parse(readFileSync(join(config, "secrets", "identity.json"), "utf8"));
  assert.ok(!(initial.stdout + initial.stderr).includes(key));
  assert.match(initial.stdout, /Provider pubkey: [a-f0-9]{64}/);
  const pair = run("pair");
  assert.equal(pair.status, 0);
  assert.equal(initial.stdout, `Buzz plugin folder: ${join(config, "buzz-plugin")}\n${pair.stdout}`);
  assert.equal(run("pair", "list").stdout.trim(), "[]");
  const label = "VM's $(ignored)";
  assert.equal(run("targets", "add", "vm", "--relay", "wss://relay.example", "--daemon", daemon.pubkey, "--label", label).status, 0);
  assert.equal(statSync(target("vm")).mode & 0o777, 0o600);
  assert.equal(existsSync(legacy("vm")), false);
  assert.equal(run("provider", "install").stdout, initial.stdout);
  assert.match(run("targets", "list").stdout, /vm \(VM's \$\(ignored\)\)\twss:\/\/relay\.example\t[a-f0-9]{64} \(no confirmation\)\t—\t0\t—/);
  assert.equal(run("targets", "remove", "vm").status, 0);
  assert.equal(existsSync(target("vm")), false);
});

test("targets validate IDs, relay, daemon and wake; commands never echo malformed arguments", (t) => {
  const { run, target } = fixture(t);
  for (const args of [
    ["../escaped", "--relay", "wss://relay.example", "--daemon", daemon.pubkey],
    ["UPPER", "--relay", "wss://relay.example", "--daemon", daemon.pubkey],
    ["mac", "--local"], ["mac", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://user:" + hidden + "@relay.example", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://https://relay.example", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://relay.example", "--daemon", agent.secret.slice(0, 33)],
    ["vm", "--relay", "wss://relay.example", "--daemon", daemon.pubkey, "--token", hidden],
  ]) assert.equal(run("targets", "add", ...args).status, 1);
  assert.equal(existsSync(target("vm")), false);
  const options = ["--relay", "wss://relay.example", "--daemon", daemon.pubkey];
  assert.equal(run("targets", "add", "vm", ...options, "--wake", "instabox", "--account", "acc_test", "--machine", "m_test").status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("vm"), "utf8")).wake, { kind: "instabox", accountId: "acc_test", machineId: "m_test" });
  assert.equal(run("targets", "add", "vm", ...options, "--wake", "command", "--cmd", "/path/to/wake").status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("vm"), "utf8")).wake, { kind: "command", cmd: "/path/to/wake" });
});

test("local targets read installed homes, store relay targets and pair the provider live", (t) => {
  const { home, run, target } = fixture(t);
  const missing = run("targets", "add", "mac", "--local");
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /not installed.*yh install --home/);
  assert.equal(existsSync(target("mac")), false);
  const relay = "wss://relay.example";
  assert.equal(run("install", "--relay", relay, "--relay-pubkey", daemon.pubkey).status, 0);
  const added = run("targets", "add", "mac", "--local", "--label", "My Mac");
  assert.equal(added.status, 0, added.stderr);
  const stored = JSON.parse(readFileSync(target("mac"), "utf8"));
  assert.equal(stored.transport, "relay");
  assert.equal(stored.relay, relay);
  const provider = added.stdout.match(/Provider pubkey: ([a-f0-9]{64})/)![1];
  assert.equal(readPairing(home, provider)?.label, "My Mac");
  assert.match(added.stdout, /no restart needed/);
  assert.match(added.stdout, new RegExp("buzz-admin add-member --pubkey " + stored.daemonPubkey));
  const pairedAt = readPairing(home, provider)!.pairedAt;
  assert.equal(run("targets", "add", "explicit", "--local", "--home", home).status, 0);
  assert.equal(readPairing(home, provider)!.pairedAt, pairedAt);
  for (const args of [["--relay", relay], ["--daemon", daemon.pubkey], ["--wake", "command", "--cmd", "true"]]) {
    assert.equal(run("targets", "add", "bad", "--local", ...args).status, 1);
  }
  assert.equal(run("targets", "add", "bad", "--home", home, "--relay", relay, "--daemon", daemon.pubkey).status, 1);
});

test("targets store WebSocket URLs and reject bad relay addresses even in existing files", (t) => {
  const { bin, env, run, target } = fixture(t);
  assert.equal(run("provider", "install").status, 0);
  const bridge = (input: unknown) => spawnSync(join(bin, "yewholt-buzz-bridge"), {
    input: JSON.stringify(input), env, encoding: "utf8", timeout: 5_000,
  });
  const add = (relay: string) => run("targets", "add", "instabox", "--relay", relay, "--daemon", daemon.pubkey);
  for (const [input, expected] of [
    ["https://3000-machine.example", "wss://3000-machine.example"],
    ["http://[::1]:3000/relay", "ws://[::1]:3000/relay"],
  ]) {
    assert.equal(add(input).status, 0);
    assert.equal(JSON.parse(readFileSync(target("instabox"), "utf8")).relay, expected);
  }
  const filename = target("instabox");
  const original = readFileSync(filename, "utf8");
  const config = JSON.parse(original);
  const malformed = "wss://https://3000-machine.example";
  for (const url of [malformed, "wss:////relay.example", "ws://host..example",
    "wss://-host.example", "https://relay.example:65536", "https://relay.example/path?token=" + hidden]) {
    const result = add(url);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /Invalid relay URL for target instabox/);
    assert.equal(readFileSync(filename, "utf8"), original);
  }
  const request = { op: "targets", details: true };
  writeFileSync(filename, JSON.stringify({ ...config, relay: "https://3000-machine.example" }));
  const loaded = bridge(request);
  assert.equal(loaded.status, 0);
  assert.deepEqual(JSON.parse(loaded.stdout), {
    ok: true, targets: ["instabox"], relays: { instabox: "wss://3000-machine.example" },
  });
  writeFileSync(filename, JSON.stringify({ ...config, relay: malformed }));
  const hint = /Re-run yewholt targets add instabox --relay <url> --daemon <pubkey>/;
  const doctor = run("targets", "doctor", "instabox");
  assert.equal(doctor.status, 1);
  assert.match(doctor.stderr, hint);
  assert.match(run("targets", "list").stdout, hint);
  const refused = bridge(request);
  assert.equal(refused.status, 1);
  assert.match(JSON.parse(refused.stdout).error, hint);
  assert.ok(!refused.stdout.includes(malformed));
});

test("additional daemon relays keep legacy pairings separate and local targets advertise both", (t) => {
  const { run, target } = fixture(t);
  const primary = "wss://primary.example";
  const secondary = "wss://shared.example";
  assert.equal(run("install", "--relay", primary, "--relay-pubkey", daemon.pubkey).status, 0);
  assert.equal(run("relay", "add", secondary, "--relay-pubkey", agent.pubkey).status, 0);
  assert.equal(run("relay", "add", secondary + "/", "--relay-pubkey", agent.pubkey).status, 0);
  assert.equal(run("relay", "add", secondary + "/", "--relay-pubkey", daemon.pubkey).status, 1);
  assert.deepEqual(JSON.parse(run("relay", "list").stdout), [
    { relayUrl: primary, externalRelayPubkey: daemon.pubkey }, { relayUrl: secondary, externalRelayPubkey: agent.pubkey },
  ]);
  assert.equal(run("targets", "add", "mac", "--local").status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("mac"), "utf8")).relays, [secondary]);
  const first = JSON.parse(run("pair", "list").stdout);
  assert.equal(first.length, 1);
  assert.deepEqual(JSON.parse(run("pair", "list", "--relay", secondary).stdout), first);
  assert.equal(run("pair", "remove", first[0].pubkey, "--relay", secondary).status, 0);
  assert.deepEqual(JSON.parse(run("pair", "list", "--relay", secondary).stdout), []);
  assert.deepEqual(JSON.parse(run("pair", "list").stdout), first);
  assert.equal(run("targets", "add", "instabox", "--relay", primary, "--relay", secondary, "--daemon", daemon.pubkey).status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("instabox"), "utf8")).relays, [secondary]);
});

test("relay remove promotes the next daemon relay with its pairings and prunes provider targets", (t) => {
  const { home, run, target } = fixture(t);
  const old = "wss://old.example";
  const current = "wss://current.example";
  const retired = "wss://retired.example";
  assert.equal(run("install", "--relay", old, "--relay-pubkey", daemon.pubkey).status, 0);
  assert.equal(run("relay", "add", current, "--relay-pubkey", agent.pubkey).status, 0);
  assert.equal(run("targets", "add", "mac", "--local", "--label", "Mac").status, 0);
  assert.equal(run("pair", "remove", JSON.parse(run("pair", "list").stdout)[0].pubkey).status, 0);
  const paired = JSON.parse(run("pair", "list", "--relay", current).stdout);
  assert.equal(paired.length, 1);
  assert.equal(run("targets", "add", "vm", "--relay", retired, "--relay", old, "--relay", current, "--daemon", daemon.pubkey).status, 0);
  assert.equal(run("targets", "add", "gone", "--relay", retired, "--daemon", daemon.pubkey).status, 0);
  assert.equal(run("relay", "remove", "wss://unknown.example").status, 1);
  const removed = run("relay", "remove", old + "/");
  assert.equal(removed.status, 0, removed.stderr);
  assert.match(removed.stdout, /wss:\/\/current\.example is now its primary relay/);
  assert.deepEqual(JSON.parse(run("relay", "list").stdout), [{ relayUrl: current, externalRelayPubkey: agent.pubkey }]);
  assert.deepEqual(JSON.parse(readFileSync(join(home, "config.json"), "utf8")), { relayUrl: current, externalRelayPubkey: agent.pubkey });
  assert.deepEqual(JSON.parse(run("pair", "list").stdout), paired);
  const mac = JSON.parse(readFileSync(target("mac"), "utf8"));
  assert.equal(mac.relay, current);
  assert.equal(mac.relays, undefined);
  assert.equal(mac.label, "Mac");
  const vm = JSON.parse(readFileSync(target("vm"), "utf8"));
  assert.deepEqual([vm.relay, vm.relays, vm.daemonPubkey], [retired, [current], daemon.pubkey]);
  assert.equal(run("relay", "remove", retired).status, 0);
  assert.equal(existsSync(target("gone")), false);
  assert.deepEqual([JSON.parse(readFileSync(target("vm"), "utf8")).relay, JSON.parse(readFileSync(target("vm"), "utf8")).relays], [current, undefined]);
  assert.equal(run("relay", "remove", current).status, 1);
  assert.equal(existsSync(target("mac")), true);
});

test("targets doctor checks the live relay, daemon, pairing and model catalog without printing refusals", async (t) => {
  const { home, run, env } = fixture(t);
  assert.equal(run("provider", "install").status, 0);
  const piDir = join(home, "daemon-pi");
  const daemonEnv = { ...env, PI_CODING_AGENT_DIR: piDir };
  const invoke = (args: string[], envOverride = env) =>
    exec(process.execPath, [cli, ...args], { env: envOverride, timeout: 20_000 });
  const doctor = (...id: string[]) => invoke(["targets", "doctor", ...id]);
  const failure = async (...id: string[]) => {
    try {
      await doctor(...id);
      assert.fail("doctor should exit nonzero");
    } catch (error) {
      const result = error as { code: unknown; stdout: string; stderr: string };
      assert.equal(result.code, 1);
      return result;
    }
  };
  const server = new WebSocketServer({ host: "127.0.0.1", port: 0 });
  t.after(async () => {
    for (const ws of server.clients) ws.terminate();
    if (server.address()) await new Promise<void>((resolve) => server.close(() => resolve()));
  });
  const closeServer = () => new Promise<void>((resolve) => server.close(() => resolve()));
  let started = false;
  try {
    await new Promise<void>((resolve) => server.once("listening", resolve));
    const addr = server.address();
    assert.ok(addr && typeof addr === "object");
    const relay = "ws://127.0.0.1:" + addr.port;
    assert.equal(run("install", "--relay", relay, "--relay-pubkey", agent.pubkey).status, 0);
    const owner = run("admin", "keys").stdout.match(/^owner ([a-f0-9]{64})$/m)![1];
    const wakeUrl = "https://vm.example/wake";
    let profile = signEvent(agent.secret, RUNTIME_PROFILE_KIND, JSON.stringify({ wake_url: wakeUrl }), []);
    let allow = true;
    let acceptRequest = true;
    server.on("connection", (ws) => {
      let pubkey: string;
      const subscriptions = new Map<string, string>();
      ws.send(JSON.stringify(["AUTH", "test"]));
      ws.on("message", (data) => {
        const [type, item, filter] = JSON.parse(data.toString());
        if (type === "AUTH") {
          pubkey = item.pubkey;
          ws.send(JSON.stringify(["OK", item.id, allow, hidden + agent.secret]));
        } else if (type === "REQ") {
          if (filter.kinds?.includes(CONTROL_KIND)) subscriptions.set(item, pubkey);
          if (filter.kinds?.includes(RUNTIME_PROFILE_KIND) && item === "daemon-runtime-profile") {
            assert.deepEqual(filter.authors, [owner]);
            ws.send(JSON.stringify(["EVENT", item, profile]));
          }
          ws.send(JSON.stringify(["EOSE", item]));
          if (item === "deploy-control" && pubkey === owner) server.emit("daemon-ready");
        } else if (type === "EVENT") {
          const event: NostrEvent = item;
          const accepted = event.kind !== CONTROL_KIND || acceptRequest;
          ws.send(JSON.stringify(["OK", event.id, accepted, accepted ? "" : hidden]));
          if (event.kind === RUNTIME_PROFILE_KIND && event.pubkey === owner) profile = event;
          if (!accepted || event.kind !== CONTROL_KIND) return;
          if (!started && subscriptions.has("deploy-confirmation")) {
            const { requestId, agentPubkey } = JSON.parse(event.content);
            const wrongSigner = controlEvent(agent.secret, pubkey, "confirmation", { requestId, agentPubkey },
              { job: requestId, agentPubkey, ok: true, catalog: { models: ["fake/fake"] } });
            ws.send(JSON.stringify(["EVENT", "deploy-confirmation", wrongSigner]));
          }
          server.emit("control-event", event);
        }
      });
      const forward = (event: NostrEvent) => {
        for (const [id, recipient] of subscriptions) {
          if (event.tags.some(([name, value]) => name === "p" && value === recipient)) {
            ws.send(JSON.stringify(["EVENT", id, event]));
          }
        }
      };
      server.on("control-event", forward);
      ws.once("close", () => server.off("control-event", forward));
    });
    assert.equal(run("targets", "add", "vm", "--relay", relay, "--daemon", owner).status, 0);
    const offline = await failure("vm");
    assert.match(offline.stdout, /^vm: Daemon offline or not responding;.*yh start.*\n$/);
    allow = false;
    const rejected = await failure("vm");
    assert.match(rejected.stdout, /reachable, NIP-42 AUTH failed or timed out/);
    assert.ok(!(rejected.stdout + rejected.stderr).includes(hidden) && !(rejected.stdout + rejected.stderr).includes(agent.secret));
    allow = true;
    acceptRequest = false;
    const blocked = await failure("vm");
    assert.match(blocked.stdout, /Relay control request not acknowledged.*buzz-admin add-member/);
    assert.ok(!blocked.stdout.includes(hidden));
    acceptRequest = true;

    const start = async (settings: typeof daemonEnv & NodeJS.ProcessEnv) => {
      started = true;
      await Promise.all([once(server, "daemon-ready", { signal: AbortSignal.timeout(20_000) }), invoke(["start"], settings)]);
    };
    await start(daemonEnv);
    const unpaired = await failure("vm");
    const pubkey = run("pair").stdout.match(/Provider pubkey: ([a-f0-9]{64})/)![1];
    assert.ok(unpaired.stdout.includes(`Provider not paired; on the target host, run yh pair add ${pubkey} --label vm --relay '${relay}/'`));
    assert.equal(run("pair", "add", pubkey, "--label", "vm", "--relay", relay).status, 0);
    const noLogin = await failure();
    assert.match(noLogin.stdout, /^vm: Pi login missing for the daemon user \(model catalog empty\);.*then enter \/login;.*yh stop && yh start.*\n$/);
    mkdirSync(piDir, { recursive: true });
    writeFileSync(join(piDir, "auth.json"), JSON.stringify({ "unsupported-provider": { type: "api_key", key: hidden } }), { mode: 0o600 });
    const empty = await failure("vm");
    assert.match(empty.stdout, /^vm: Model catalog empty;.*then enter \/login.*yh stop && yh start.*\n$/);
    assert.ok(!empty.stdout.includes(hidden));
    await invoke(["stop"], daemonEnv);
    rmSync(join(piDir, "auth.json"));
    await start({ ...daemonEnv, DEEPSEEK_API_KEY: hidden, YEWHOLT_WAKE_URL: wakeUrl, YEWHOLT_WAKE_PORT: "8787" });
    assert.equal(profile.pubkey, owner);
    assert.equal(JSON.parse(profile.content).wake_url, wakeUrl);
    const accepted = await doctor("vm");
    assert.match(accepted.stdout, /reachable, NIP-42 authenticated; connect \+ AUTH latency \d+ ms/);
    assert.match(accepted.stdout, /daemon online, provider paired, models available/);
  } finally {
    if (started) await invoke(["stop"], daemonEnv);
  }
  const sleeping = await failure("vm");
  assert.equal(sleeping.stdout, "vm: VM appears to be sleeping; send a message to one of its agents to wake it.\n");
  for (const ws of server.clients) ws.terminate();
  await closeServer();
  const unreachable = await failure("vm");
  assert.match(unreachable.stdout, /^vm: Relay unreachable or timed out;.*yh targets add vm --relay <reachable-url> --daemon [a-f0-9]{64}.*\n$/);
});
