const cli = fileURLToPath(new URL("../src/cli.js", import.meta.url));
const exec = promisify(execFile);
const agent = generateKeyPair();
const daemon = generateKeyPair();
const hidden = "private-environment-fixture";

function fixture(t: { after(fn: () => void): void }) {
  const home = mkdtempSync(join(homedir(), "yewholt-provider-cli-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const bin = join(home, "bin with 'quotes'");
  const config = join(home, "xdg", "yewholt");
  const env = { PATH: process.env.PATH, HOME: home, XDG_CONFIG_HOME: join(home, "xdg"),
    YEWHOLT_HOME: home, YEWHOLT_PROVIDER_BIN_DIR: bin, YEWHOLT_PROVIDER_FILE_STORAGE: "1" };
  const run = (...args: string[]) => {
    const result = spawnSync(process.execPath, [cli, ...args], { env, encoding: "utf8", timeout: 5_000 });
    assert.equal(result.error, undefined);
    assert.ok(![agent.secret, hidden].some((value) => (result.stdout + result.stderr).includes(value)));
    return result;
  };
  const legacy = (id: string) => join(bin, "buzz-backend-yewholt-" + id);
  const target = (id: string) => join(config, "targets", id + ".json");
  return { home, bin, config, env, run, legacy, target };
}

test("provider install, target add, pair and remove end to end; install deletes old managed shims only", (t) => {
  const { bin, config, run, legacy, target } = fixture(t);
  mkdirSync(bin, { recursive: true });
  const managed = "#!/bin/sh\n# Managed by yewholt\nexit 0\n";
  writeFileSync(legacy("mac"), managed, { mode: 0o700 });
  writeFileSync(join(bin, "yewholt-provider-engine"), managed, { mode: 0o700 });
  writeFileSync(legacy("foreign"), "not generated by Yewholt", { mode: 0o700 });
  const initial = run("provider", "install");
  assert.equal(initial.status, 0, initial.stderr);
  assert.equal(existsSync(legacy("mac")), false);
  assert.equal(existsSync(join(bin, "yewholt-provider-engine")), false);
  assert.equal(readFileSync(legacy("foreign"), "utf8"), "not generated by Yewholt");
  assert.equal(statSync(join(bin, "yewholt-buzz-bridge")).mode & 0o777, 0o700);
  const key = JSON.parse(readFileSync(join(config, "secrets", "identity.json"), "utf8"));
  assert.ok(!(initial.stdout + initial.stderr).includes(key));
  assert.match(initial.stdout, /Provider pubkey: [a-f0-9]{64}/);
  const pair = run("pair");
  assert.equal(pair.status, 0);
  assert.equal(initial.stdout, `Buzz plugin folder: ${join(config, "buzz-plugin")}\n${pair.stdout}`);
  assert.equal(run("pair", "list").stdout.trim(), "[]");
  const label = "VM's $(ignored)";
  assert.equal(run("targets", "add", "vm", "--relay", "wss://relay.example", "--daemon", daemon.pubkey, "--label", label).status, 0);
  assert.equal(statSync(target("vm")).mode & 0o777, 0o600);
  assert.equal(existsSync(legacy("vm")), false);
  assert.equal(run("provider", "install").stdout, initial.stdout);
  assert.match(run("targets", "list").stdout, /vm \(VM's \$\(ignored\)\)\twss:\/\/relay\.example\t[a-f0-9]{64} \(no confirmation\)\t—\t0\t—/);
  assert.equal(run("targets", "remove", "vm").status, 0);
  assert.equal(existsSync(target("vm")), false);
});

test("targets validate IDs, relay, daemon and wake; commands never echo malformed arguments", (t) => {
  const { run, target } = fixture(t);
  for (const args of [
    ["../escaped", "--relay", "wss://relay.example", "--daemon", daemon.pubkey],
    ["UPPER", "--relay", "wss://relay.example", "--daemon", daemon.pubkey],
    ["mac", "--local"], ["mac", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://user:" + hidden + "@relay.example", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://https://relay.example", "--daemon", daemon.pubkey],
    ["vm", "--relay", "wss://relay.example", "--daemon", agent.secret.slice(0, 33)],
    ["vm", "--relay", "wss://relay.example", "--daemon", daemon.pubkey, "--token", hidden],
  ]) assert.equal(run("targets", "add", ...args).status, 1);
  assert.equal(existsSync(target("vm")), false);
  const options = ["--relay", "wss://relay.example", "--daemon", daemon.pubkey];
  assert.equal(run("targets", "add", "vm", ...options, "--wake", "instabox", "--account", "acc_test", "--machine", "m_test").status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("vm"), "utf8")).wake, { kind: "instabox", accountId: "acc_test", machineId: "m_test" });
  assert.equal(run("targets", "add", "vm", ...options, "--wake", "command", "--cmd", "/path/to/wake").status, 0);
  assert.deepEqual(JSON.parse(readFileSync(target("vm"), "utf8")).wake, { kind: "command", cmd: "/path/to/wake" });
});

test("local targets read installed homes, store relay targets and pair the provider live", (t) => {
  const { home, run, target } = fixture(t);
  const missing = run("targets", "add", "mac", "--local");
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /not installed.*yh install --home/);
  assert.equal(existsSync(target("mac")), false);
  const relay = "wss://relay.example";
  assert.equal(run("install", "--relay", relay, "--relay-pubkey", daemon.pubkey).status, 0);
  const added = run("targets", "add", "mac", "--local", "--label", "My Mac");
  assert.equal(added.status, 0, added.stderr);
  const stored = JSON.parse(readFileSync(target("mac"), "utf8"));
  assert.equal(stored.transport, "relay");
  assert.equal(stored.relay, relay);
  const provider = added.stdout.match(/Provider pubkey: ([a-f0-9]{64})/)![1];
  assert.equal(readPairing(home, provider)?.label, "My Mac");
  assert.match(added.stdout, /no restart needed/);
  assert.match(added.stdout, new RegExp("buzz-admin add-member --pubkey " + stored.daemonPubkey));
  const pairedAt = readPairing(home, provider)!.pairedAt;
  assert.equal(run("targets", "add", "explicit", "--local", "--home", home).status, 0);
  assert.equal(readPairing(home, provider)!.pairedAt, pairedAt);
  for (const args of [["--relay", relay], ["--daemon", daemon.pubkey], ["--wake", "command", "--cmd", "true"]]) {
    assert.equal(run("targets", "add", "bad", "--local", ...args).status, 1);
  }
  assert.equal(run("targets", "add", "bad", "--home", home, "--relay", relay, "--daemon", daemon.pubkey).status, 1);
});

test("targets store WebSocket URLs and reject bad relay addresses even in existing files", (t) => {
  const { bin, env, run, target } = fixture(t);
  assert.equal(run("provider", "install").status, 0);
  const bridge = (input: unknown) => spawnSync(join(bin, "yewholt-buzz-bridge"), {
    input: JSON.stringify(input), env, encoding: "utf8", timeout: 5_000,
  });
  const add = (relay: string) => run("targets", "add", "instabox", "--relay", relay, "--daemon", daemon.pubkey);
  for (const [input, expected] of [
    ["https://3000-machine.instabox.tech", "wss://3000-machine.instabox.tech"],
    ["http://[::1]:3000/relay", "ws://[::1]:3000/relay"],
  ]) {
    assert.equal(add(input).status, 0);
    assert.equal(JSON.parse(readFileSync(target("instabox"), "utf8")).relay, expected);
  }
  const filename = target("instabox");
  const original = readFileSync(filename, "utf8");
  const config = JSON.parse(original);
  const malformed = "wss://https://3000-machine.instabox.tech";
  for (const url of [malformed, "wss:////relay.example", "ws://host..example",
    "wss://-host.example", "https://relay.example:65536", "https://relay.example/path?token=" + hidden]) {
    const result = add(url);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /Invalid relay URL for target instabox/);
    assert.equal(readFileSync(filename, "utf8"), original);
  }
  const request = { op: "targets", details: true };
  writeFileSync(filename, JSON.stringify({ ...config, relay: "https://3000-machine.instabox.tech" }));
  const loaded = bridge(request);
  assert.equal(loaded.status, 0);
  assert.deepEqual(JSON.parse(loaded.stdout), {
    ok: true, targets: ["instabox"], relays: { instabox: "wss://3000-machine.instabox.tech" },
  });
  writeFileSync(filename, JSON.stringify({ ...config, relay: malformed }));
  const hint = /Re-run yewholt targets add instabox --relay <url> --daemon <pubkey>/;
  const doctor = run("targets", "doctor", "instabox");
  assert.equal(doctor.status, 1);
  assert.match(doctor.stderr, hint);
  assert.match(run("targets", "list").stdout, hint);
  const refused = bridge(request);
  assert.equal(refused.status, 1);
  assert.match(JSON.parse(refused.stdout).error, hint);
  assert.ok(!refused.stdout.includes(malformed));
});

test("targets doctor measures relay AUTH and never prints a relay-supplied refusal", async (t) => {
  const { run, env } = fixture(t);
  assert.equal(run("provider", "install").status, 0);
  const server = new WebSocketServer({ host: "127.0.0.1", port: 0 });
  try {
    await new Promise<void>((resolve) => server.once("listening", resolve));
    const addr = server.address();
    assert.ok(addr && typeof addr === "object");
    let allow = true;
    server.on("connection", (ws) => {
      ws.send(JSON.stringify(["AUTH", "test"]));
      ws.on("message", (data) => {
        const [type, event] = JSON.parse(data.toString());
        assert.equal(type, "AUTH");
        ws.send(JSON.stringify(["OK", event.id, allow, hidden + agent.secret]));
      });
    });
    assert.equal(run("targets", "add", "vm", "--relay", "ws://127.0.0.1:" + addr.port, "--daemon", daemon.pubkey).status, 0);
    const doctor = () => exec(process.execPath, [cli, "targets", "doctor", "vm"], { env, timeout: 7_000 });
    const accepted = await doctor();
    assert.match(accepted.stdout, /reachable, NIP-42 authenticated; connect \+ AUTH latency \d+ ms/);
    assert.match(accepted.stdout, /no confirmation \(recorded evidence only; no live daemon probe\)/);
    assert.match(accepted.stdout, /Daemon version: unavailable/);
    allow = false;
    const rejected = await doctor();
    assert.match(rejected.stdout, /reachable, NIP-42 AUTH failed or timed out/);
    assert.ok(!(rejected.stdout + rejected.stderr).includes(hidden) && !(rejected.stdout + rejected.stderr).includes(agent.secret));
  } finally {
    for (const ws of server.clients) ws.terminate();
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
});
